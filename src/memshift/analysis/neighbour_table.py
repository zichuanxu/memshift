"""The neighbour comparison table (prereg v2 section 6) and the counts the paper quotes from it,
generated from paper/audit/neighbours/properties.json so that no cell is typed by hand.

Rows are the fifteen nearest benchmarks of the audit plus the MemShift row (the object with
"is_reference"). A cell is read from ``fields[<field>]``: a categorical value (yes / partial / no /
not stated) or a short string (world text, native systems, histories, questions). Three optional
flags in a field control the marks; they are honoured on the MemShift row only:

  planned        the whole cell is a plan of the pre-registered stage 4 (dagger)
  planned_extra  a string added on top of the observed value, shown as ``value (+extra dagger)``
  observed_extra a string added on top of the observed value once it has run, ``value (+extra)``
  inferred       the audit inferred the value; the paper does not state it (double dagger)

Everything not yet run is therefore flipped by editing the JSON alone: set the observed value, drop
``planned_extra`` / ``planned`` (or turn ``planned_extra`` into ``observed_extra``), and rerun this
module; the marks disappear with the flags. The
caption carries no legend for the dagger (a plan is not something the printed table explains).

Usage: python -m memshift.analysis.neighbour_table paper/audit/neighbours/properties.json \\
           paper/generated/tab_neighbours.tex
Writes the Section 2 table to the given path, the appendix table next to it as <stem>_full.tex and
the counts as LaTeX macros (\\Nbr... over the neighbours, \\Ms... for the MemShift row) as
neighbour_counts.tex in the same directory.
"""

from __future__ import annotations

import argparse
import json
import statistics
from dataclasses import dataclass
from pathlib import Path
from typing import Any

HEAD = "% generated by memshift.analysis.neighbour_table; do not edit\n"
CATEGORIES = ("yes", "partial", "no", "not stated")
JUDGE_VALUES = ("none", "minor", "primary", "not stated")
# a benchmark scored without an LLM judge earns the check mark
JUDGE_AS_CATEGORY = {"none": "yes", "minor": "partial", "primary": "no", "not stated": "not stated"}
GREY = r"\textcolor{cgrey}{%s}"
SYMBOL = {
    "yes": r"\checkmark",
    "partial": r"$\sim$",
    "no": GREY % r"$\times$",
    "not stated": GREY % "n/s",
}
DAGGER = r"$^\dagger$"
DDAGGER = r"$^\ddagger$"
TEXT_CODES = {
    "T": "template-rendered",
    "L": "written by an LLM",
    "L+H": "by an LLM with human editing or review",
    "H": "human-written",
    "R": "real records",
    "M": "mixture of these or of existing datasets",
}
INFERRED_NOTE = r"$^\ddagger$~inferred by the audit, not stated in the paper."


@dataclass(frozen=True)
class Column:
    """One table column: the audit field it reads, its rotated header, and how to render it."""

    field: str
    header: str
    kind: str = "cat"  # cat (symbol) | judge (symbol from the judge class) | text (string)
    stem: str = ""  # macro stem for the counts (categorical columns only)


COLUMNS = {
    "text": Column("text_origin", "world text", "text"),
    "gold_first": Column("gold_first", "gold before text", stem="GoldFirst"),
    "gold_dep": Column("gold_dependency", "gold dependency sets", stem="GoldDep"),
    "derived": Column("derived_knowledge", "derived items", stem="Derived"),
    "update": Column("chg_new_updated_facts", "source update", stem="Update"),
    "invalid": Column("chg_retraction_deletion", "deletion", stem="Invalid"),
    "implicit": Column("chg_implicit_conflict", "implicit conflict", stem="Implicit"),
    "redef": Column("chg_definition_change", "user redefines", stem="Redef"),
    "writer": Column("chg_writer_model_change", "writer switch", stem="Writer"),
    "impl": Column("chg_implementation_migration", "implementation switch", stem="Impl"),
    "consent": Column("chg_consent_revocation", "consent revoked", stem="Consent"),
    "branch": Column("counterfactual", "counterfactual", stem="Branch"),
    "native": Column("native_systems", "native systems", "text"),
    "judge": Column("llm_judge", "no LLM judge", "judge", stem="Judge"),
    "prereg": Column("prereg", "frozen plan", stem="Prereg"),
    "histories": Column("n_histories", "histories", "text"),
    "questions": Column("n_questions", "questions", "text"),
}
# (group label, column keys); the Section 2 table and the appendix table
MAIN = (
    ("data", ("text", "gold_first", "gold_dep")),
    ("changes tested", ("update", "invalid", "redef", "writer", "impl")),
    ("protocol", ("branch", "judge", "prereg")),
    ("scale", ("native", "histories", "questions")),
)
FULL = (
    ("data", ("text", "gold_first", "gold_dep", "derived")),
    ("changes tested", ("update", "invalid", "implicit", "redef", "writer", "impl", "consent")),
    ("protocol", ("branch", "judge", "prereg")),
    ("scale", ("native", "histories", "questions")),
)
# macro stem and vocabulary for every counted categorical column
VALUE_KEY = {
    "yes": "Yes",
    "partial": "Part",
    "no": "No",
    "not stated": "NS",
    "none": "None",
    "minor": "Minor",
    "primary": "Primary",
}


def _tex(s: str) -> str:
    for a, b in (
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("_", r"\_"),
        ("#", r"\#"),
    ):
        s = s.replace(a, b)
    return s


def load(path: Path) -> list[dict[str, Any]]:
    """The audit objects, neighbours first and the MemShift row last; validated."""
    objs = json.loads(path.read_text())
    ref = [o for o in objs if o.get("is_reference")]
    if len(ref) != 1:
        raise ValueError(f"expected exactly one MemShift row, found {len(ref)}")
    rows = [o for o in objs if not o.get("is_reference")] + ref
    used = {c.field for c in COLUMNS.values()}
    for o in rows:
        for name in used:
            if name not in o["fields"]:
                raise ValueError(f"{o['key']}: missing field {name!r}")
        for col in COLUMNS.values():
            f = o["fields"][col.field]
            if col.kind != "text" and f["value"] not in _vocabulary(col):
                raise ValueError(f"{o['key']}.{col.field}: bad value {f['value']!r}")
            if o is not ref[0] and any(
                k in f for k in ("planned", "planned_extra", "observed_extra")
            ):
                raise ValueError(f"{o['key']}.{col.field}: only the MemShift row can be planned")
    return rows


def _vocabulary(col: Column) -> tuple[str, ...]:
    return JUDGE_VALUES if col.kind == "judge" else CATEGORIES


def cell(row: dict[str, Any], col: Column) -> str:
    f = row["fields"][col.field]
    value = str(f["value"])
    if col.kind == "text":
        out = GREY % "n/s" if value == "n/s" else _tex(value)
        if f.get("planned_extra"):
            out += rf"\,(+{_tex(str(f['planned_extra']))}{DAGGER})"
        elif f.get("observed_extra"):
            out += rf"\,(+{_tex(str(f['observed_extra']))})"
    else:
        out = SYMBOL[JUDGE_AS_CATEGORY[value] if col.kind == "judge" else value]
    if f.get("planned") and not f.get("planned_extra"):
        out += DAGGER
    if f.get("inferred"):
        out += DDAGGER
    return out


def _text_values(row: dict[str, Any]) -> list[str]:
    """The observed world-text code and, on the MemShift row, the planned one."""
    f = row["fields"]["text_origin"]
    extra = f.get("planned_extra") or f.get("observed_extra")
    return [f["value"]] + ([extra] if extra else [])


def _marks(rows: list[dict[str, Any]], columns: list[Column]) -> tuple[bool, bool]:
    fields = [r["fields"][c.field] for r in rows for c in columns]
    planned = any(f.get("planned") or f.get("planned_extra") for f in fields)
    return planned, any(f.get("inferred") for f in fields)


LEGEND_PARTS = (
    r"\checkmark{}~yes, $\sim$~partial, $\times$~the described design has no such ",
    r"element, n/s~not stated. World text: LEGEND. Counterfactual: the same history ",
    r"with and without the change (\memshift{}: byte-identical branches). Frozen plan: ",
    r"hypotheses and thresholds fixed before the runs (pre-registration or a signed ",
    r"analysis plan). Native systems: off-the-shelf memory systems evaluated, as the ",
    r"paper groups them; long-context and plain RAG baselines, each paper's own ",
    r"systems and oracles are not counted. Histories (worlds, users or trajectories) ",
    r"and questions as printed (MemoryArena: tasks; EvoArena: the PersonaMem-Evo ",
    r"subset); \memshift{}: test worlds and UNIT.",
)
# the columns only the appendix table has, and why the MemShift row is partial on derived items
FULL_PARTS = (
    r" Derived items: the graded items aggregate several records (counts, sets, sums, ",
    r"multi-hop or temporal aggregation) rather than restate one stored fact; $\sim$ when ",
    r"both kinds are graded, as in \memshift{}: every item is derived by a writer, but of a ",
    r"world's 48 items only the six definition items and four recurring series aggregate ",
    r"records; the rest are attribute or latest-value items. Implicit conflict: ",
    r"conflicting information without an explicit replacement, which the system must ",
    r"detect. Consent revoked: the user withdraws consent or asks to forget, and the memory ",
    r"must stop using or delete the data.",
)


def _caption(rows: list[dict[str, Any]], inferred: bool, full: bool) -> str:
    codes = {str(v) for r in rows for v in _text_values(r)}
    legend = ", ".join(f"{k}~{v}" for k, v in TEXT_CODES.items() if k in codes)
    unit = str(rows[-1]["fields"]["n_questions"].get("unit", "knowledge items"))
    parts: list[str]
    if full:  # self-contained: the appendix table is the one the paper shows
        head = (
            r"\memshift{} against its nearest neighbours, all properties of the audit; every "
            r"cell is read from the neighbour's own paper (quotes in the released audit record). "
        )
        parts = [head, *LEGEND_PARTS, *FULL_PARTS]
    else:
        head = (
            r"\memshift{} against its nearest neighbours; every cell is read from the "
            r"neighbour's own paper (quotes in the released audit record, \cref{app:related}). "
        )
        parts = [head, *LEGEND_PARTS]
    text = "".join(parts).replace("LEGEND", legend).replace("UNIT", unit)
    if inferred:
        text += " " + INFERRED_NOTE
    return text


def _author_named(short_name: str) -> bool:
    """A row named after its authors (``Goyal & Ray``, ``Jiang et al.``), not a benchmark."""
    return short_name.endswith("et al.") or " & " in short_name


def table(
    rows: list[dict[str, Any]],
    groups: tuple[tuple[str, tuple[str, ...]], ...],
    label: str,
    full: bool,
) -> str:
    """One LaTeX table over the given column groups."""
    columns = [COLUMNS[k] for _, keys in groups for k in keys]
    _planned, inferred = _marks(rows, columns)
    spec = "@{}l " + " ".join("c" * len(keys) for _, keys in groups) + "@{}"
    head = ["benchmark"] + [rf"\rotatebox{{90}}{{{c.header}}}" for c in columns]
    lines = [
        r"\begin{table}[t]",
        r"\centering",
        r"\footnotesize",
        rf"\setlength{{\tabcolsep}}{{{'2pt' if full else '2.4pt'}}}",  # full: 18 columns in 5.5in
        rf"\caption{{{_caption(rows, inferred, full)}}}",
        rf"\label{{{label}}}",
        rf"\begin{{tabular}}{{{spec}}}",
        r"\toprule",
    ]
    start, spans, rules = 2, [], []
    for name, keys in groups:
        end = start + len(keys) - 1
        spans.append(rf"\multicolumn{{{len(keys)}}}{{c}}{{{name}}}")
        rules.append(rf"\cmidrule(lr){{{start}-{end}}}")
        start = end + 1
    lines += ["& " + " & ".join(spans) + r" \\", "".join(rules), " & ".join(head) + r" \\"]
    lines.append(r"\midrule")
    for r in rows:
        if r.get("is_reference"):
            lines.append(r"\midrule")
            name = r"\textbf{\memshift{}}"
        elif _author_named(r["short_name"]):  # the citation already prints the authors
            name = rf"\citet{{{r['key']}}}"
        else:
            name = rf"{_tex(r['short_name'])}~\citep{{{r['key']}}}"
        lines.append(" & ".join([name] + [cell(r, c) for c in columns]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def tab_neighbours(rows: list[dict[str, Any]]) -> str:
    return table(rows, MAIN, "tab:neighbours", full=False)


def tab_neighbours_full(rows: list[dict[str, Any]]) -> str:
    return table(rows, FULL, "tab:neighbours-full", full=True)


def _number(s: str) -> int | None:
    """An integer printed with thousands separators, or None ('208+' counts as its lower bound)."""
    digits = s.replace(",", "").removesuffix("+")
    return int(digits) if digits.isdigit() else None


def _fmt(x: float) -> str:
    return f"{x:,.0f}" if float(x).is_integer() else f"{x:,.1f}"


def counts(rows: list[dict[str, Any]]) -> dict[str, str]:
    """Macro name -> value: counts over the neighbours (Nbr...) and MemShift's own cells (Ms...)."""
    nb, ms = rows[:-1], rows[-1]["fields"]
    out: dict[str, str] = {"NbrTotal": str(len(nb))}
    for col in COLUMNS.values():
        if col.kind == "text":
            continue
        for v in _vocabulary(col):
            n = sum(o["fields"][col.field]["value"] == v for o in nb)
            out[f"Nbr{col.stem}{VALUE_KEY[v]}"] = str(n)
    native = [int(o["fields"]["native_systems"]["value"]) for o in nb]
    some = [n for n in native if n]
    out["NbrNativeZero"] = str(native.count(0))
    out["NbrNativeSome"] = str(len(some))
    out["NbrNativeThreePlus"] = str(sum(n >= 3 for n in native))
    out["NbrNativeMin"] = str(min(some))
    out["NbrNativeMax"] = str(max(native))
    qs = sorted(q for q in (_number(o["fields"]["n_questions"]["value"]) for o in nb) if q)
    out["NbrQMin"], out["NbrQMax"] = f"{qs[0]:,}", f"{qs[-1]:,}"
    out["NbrQMedian"] = _fmt(statistics.median(qs))
    hs = sorted(h for h in (_number(o["fields"]["n_histories"]["value"]) for o in nb) if h)
    ms_hist = _number(str(ms["n_histories"]["value"])) or 0
    out["NbrHistCount"] = str(len(hs))
    out["NbrHistMin"], out["NbrHistMax"] = _fmt(hs[0]), _fmt(hs[-1])
    out["NbrHistMedian"] = _fmt(statistics.median(hs))
    out["NbrHistMore"] = str(sum(h > ms_hist for h in hs))
    text = [o["fields"]["text_origin"]["value"] for o in nb]
    out["NbrTextTemplate"] = str(text.count("T"))
    out["NbrTextNS"] = str(text.count("n/s"))
    out["NbrTextWritten"] = str(len(nb) - text.count("T") - text.count("n/s"))
    out["MsNativeObs"] = str(ms["native_systems"]["value"])
    out["MsNativePlanned"] = str(ms["native_systems"].get("planned_extra", 0))
    out["MsHistObs"] = str(ms["n_histories"]["value"])
    out["MsHistPlanned"] = str(ms["n_histories"].get("planned_extra", 0))
    out["MsQ"] = str(ms["n_questions"]["value"])
    out["MsItems"] = str(ms["n_questions"].get("items", ""))
    return out


def macros(rows: list[dict[str, Any]]) -> str:
    return "".join(rf"\newcommand{{\{k}}}{{{v}}}" + "\n" for k, v in counts(rows).items())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("properties", type=Path, help="paper/audit/neighbours/properties.json")
    ap.add_argument("out", type=Path, help="paper/generated/tab_neighbours.tex")
    a = ap.parse_args()
    rows = load(a.properties)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    outputs = {
        a.out: tab_neighbours(rows),
        a.out.with_name(a.out.stem + "_full.tex"): tab_neighbours_full(rows),
        a.out.with_name("neighbour_counts.tex"): macros(rows),
    }
    for path, text in outputs.items():
        path.write_text(HEAD + text)
        print(path)


if __name__ == "__main__":
    main()
