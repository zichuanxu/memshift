"""The sixteen-system audit (plan §3.4) as a LaTeX table for the paper appendix, generated from
audit/system_audit.json so the paper never diverges from the audit record.

Main table: the systems of plan §3.4 plus our own (group != 'extra (starting audit)'); the extra
rows of the starting audit stay in system_audit.md. Cells: pass / fail / undeterminable / pending;
a basis of 'inferred' is marked with a dagger, 'by construction' with a double dagger.

Usage: python -m memshift.analysis.audit_table > paper/generated/audit_table.tex
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

MARK = {"pass": r"\checkmark", "fail": r"$\times$", "undeterminable": "?"}
EXTRA = "extra (starting audit)"
NAMES = {"零系统（ours）": "zero system (ours)"}


def _tex(s: str) -> str:
    for a, b in (
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("_", r"\_"),
        ("#", r"\#"),
    ):
        s = s.replace(a, b)
    return s


def cell(row: dict[str, Any], test: str) -> str:
    value = str(row[test])
    if value.startswith("pending"):
        return value.replace("pending ", "pend.~")
    basis = str(row.get(f"{test}_basis", ""))
    mark = MARK.get(value, _tex(value))
    if "infer" in basis:
        mark += r"$^\dagger$"
    elif "construction" in basis:
        mark += r"$^\ddagger$"
    return mark


def factor(value: str) -> str:
    return {"partial": "part.", "temporal validity only": "t.v.", "N/A": "--"}.get(value, value)


def table(rows: list[dict[str, Any]]) -> str:
    tests = ("T1", "T2", "T3", "T4")
    pending = any(str(r.get(t, "")).startswith("pending") for r in rows for t in tests)
    lines = [
        r"\begin{table}[h]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{5pt}",
        r"\caption{Diagnostic tests for sixteen real systems and our cells: retention test,"
        r" leaving test, utility floor (floor) and cost ceiling (cost). \checkmark{} pass,"
        r" $\times$ fail, ? undeterminable"
        + (r", pend.\ pending our experiment" if pending else "")
        + r". The basis of a verdict is marked $^\dagger$ when it is a stated inference and"
        r" $^\ddagger$ when it holds by construction (so ?$^\dagger$ and ?$^\ddagger$ are"
        r" undeterminable for that reason), and is measured, documented or read from code"
        r" otherwise. Owner: who holds the store in the default deployment (the model vendor,"
        r" the device platform, the developer of the agent that embeds it, or the person)."
        r" $D$, $B$: part.\ = partial, t.v.\ = temporal validity only, -- = not"
        r" applicable (the system stores no derived item). $D$ and $B$ follow the audit rubric,"
        r" which reads them from documented behaviour (partial $D$: typed structure or citations"
        r" without a span-level check) and counts an incomplete key as $B{=}0$. The native-system"
        r" experiment labels a native system at document level and infers its label from"
        r" measurement (Figure~\ref{fig:native-systems}), so the two can differ (Cognee: (part., 0)"
        r" here, (0,1) there)."
        r" Reasons and evidence for every cell are in the released audit record"
        r" (\texttt{system\_audit.json}).}",
        r"\label{tab:audit}",
        r"\begin{tabular}{@{}ll cc cccc@{}}",
        r"\toprule",
        r"system & owner & $D$ & $B$ & retention & leaving & floor & cost \\",
        r"\midrule",
    ]
    for r in rows:
        if r["group"] == EXTRA:
            continue
        name = NAMES.get(r["short_name"], r["short_name"])
        if name == "zero system (ours)":  # our own cells after the external systems
            lines.append(r"\midrule")
        tex_name = _tex(name).replace("HoldMem", r"\holdmem{}")
        cells = [tex_name, _tex(r["owner"]), factor(r["D"]), factor(r["B"])]
        cells += [cell(r, t) for t in ("T1", "T2", "T3", "T4")]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(".")
    rows = json.loads((root / "audit" / "system_audit.json").read_text())
    print("% generated by memshift.analysis.audit_table; do not edit")
    print(table(rows), end="")


if __name__ == "__main__":
    main()
