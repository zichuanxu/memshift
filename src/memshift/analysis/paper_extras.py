def load(root: Path, sources: Mapping[str, str]) -> dict[str, Any]:
    """The staged analyses behind the overview table (None where a stage is not there)."""
    src = dict(sources)
    return {
        "e1": stage_json(root, src, "e1", "e1_metrics.json"),
        "c": stage_json(root, src, "c", "e1_metrics.json"),
        "n": stage_json(root, src, "n", "e5_natives.json"),
    }


def _native_refs(n: Mapping[str, Any] | None) -> dict[str, Any]:
    """Reference system -> "branch:metric" -> estimate, from the native-system comparison. Every
    system is compared with the same references; a disagreement is an error in the analysis."""
    out: dict[str, dict[str, Any]] = {}
    for key, _ in NATIVE_SYSTEMS:
        comps = _get(n, "explore_native_null", "systems", key, "comparisons") or {}
        for comp, c in comps.items():
            for ref, r in (c.get("references") or {}).items():
                seen = out.setdefault(ref, {}).setdefault(comp, r)
                if seen["est"] != r["est"]:
                    raise ValueError(f"native references differ: {ref} {comp}")
    return out


def overview_values(inp: Mapping[str, Any]) -> dict[tuple[str, str, str, str], str]:
    """Every cell of the overview table: (block, system, branch, metric) -> printed value, Update
    and Stability in percent. Blocks: "main" and "native"."""
    out: dict[tuple[str, str, str, str], str] = {}
    for stage, system, _ in MAIN_ROWS:
        for b, _ in BRANCHES:
            for m in METRICS:
                e = _get(inp.get(stage), "cells", b, system, m)
                out["main", system, b, m] = _level(e["est"] if e else None)
    refs = _native_refs(inp.get("n"))
    for system, _ in NATIVE_REFS:
        for b, _ in BRANCHES:
            for m in METRICS:
                e = _get(refs, system, f"{b}:{m}")
                out["native", system, b, m] = _level(e["est"] if e else None)
    for system, _ in NATIVE_SYSTEMS:
        for b, _ in BRANCHES:
            for m in METRICS:
                e = _get(inp.get("n"), "systems", system, "branches", b, "native", m)
                out["native", system, b, m] = _level(e["est"] if e else None)
    return out


def _worlds(d: Mapping[str, Any] | None) -> str:
    n = (d or {}).get("n_worlds")
    return MISSING if n is None else str(n)


def _sentence(s: str) -> str:
    """`s` with its first letter in upper case (a header in sentence case)."""
    return s[:1].upper() + s[1:]


def _indent(label: str) -> str:
    """A row label indented under its group banner."""
    return r"\mtin" + ("" if label.startswith("\\") else " ") + label


def tab_overview(inp: Mapping[str, Any]) -> str:
    """The overview in two row groups under one header: the main study's cells and baselines,
    and the native systems with the cells and baselines they are compared with. Within a group,
    a small gap separates cells of one kind and the baselines."""
    v = overview_values(inp)
    n_native = _get(inp.get("n"), "membership", "worlds")
    native_worlds = MISSING if not n_native else str(len(n_native))
    last = len(BRANCHES) - 1

    def level_rows(block: str, rows: Iterable[tuple[str, str]]) -> list[str]:
        return [
            _row(_indent(label), *(v[block, system, b, m] for b, _ in BRANCHES for m in METRICS))
            for system, label in rows
        ]

    def groups(block: str, parts: Iterable[Iterable[tuple[str, str]]]) -> list[str]:
        out: list[str] = []
        for i, rows in enumerate(parts):
            out += ([r"\mtgap"] if i else []) + level_rows(block, rows)
        return out

    def end(i: int, spec: str) -> str:
        return spec + "@{}" if i == last else spec

    gap = r" @{\hspace{24pt}} "  # between the shifts' Update-Stability pairs
    lines = [
        r"\begin{table*}[t]",
        r"\caption{Update and Stability (\%) after the three shifts that change the world.}",
        r"\label{tab:overview}",
        r"\centering\mtsetup",
        r"\setlength{\tabcolsep}{6pt}",
        r"\begin{mttabular}{@{}l " + gap.join(["N{00.0}N{00.0}"] * len(BRANCHES)) + "@{}}",
        r"\toprule",
        "& "
        + " & ".join(
            rf"\multicolumn{{2}}{{{end(i, 'c')}}}{{{_sentence(name)}}}"
            for i, (_, name) in enumerate(BRANCHES)
        )
        + r" \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(l){6-7}",
        _row(
            "Memory",
            *(
                rf"\multicolumn{{1}}{{{end(i, 'c') if m == METRICS[-1] else 'c'}}}{{{m}}}"
                for i in range(len(BRANCHES))
                for m in METRICS
            ),
        ),
        r"\midrule",
        rf"\mtgroup{{7}}{{Main study: {_worlds(inp.get('e1'))} twelve-month test worlds, "
        "Qwen3.5-9B as writer and reader}",
        *groups("main", ([(s, label) for _, s, label in g] for g in MAIN_GROUPS)),
        r"\midrule",
        rf"\mtgroup{{7}}{{Native systems: {native_worlds} three-month worlds, scored on the half "
        "of the items not used to infer the labels}",
        *groups("native", (NATIVE_CELLS, BASELINES, NATIVE_SYSTEMS)),
        r"\bottomrule",
        r"\end{mttabular}",
        notes(
            rf"\holdmem{{}}($D$,$B$): $D{{=}}1$ exact recomputation, {DM} the writer's programs, "
            r"$B{=}1$ a key (the source key unless the citation key is named). $n$ per "
            r"main-study \holdmem{} cell: \ExDetMainSrcUpdateItems{}, \ExDetMainDefUpdateItems{}, "
            r"and \ExDetMainOrphanUpdateItems{} changed and \ExDetMainSrcStabilityItems{}, "
            r"\ExDetMainDefStabilityItems{}, and \ExDetMainOrphanStabilityItems{} unchanged items."
        ),
        r"\end{table*}",
    ]
    return "\n".join(lines) + "\n"


