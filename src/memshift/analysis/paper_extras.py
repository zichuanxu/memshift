def _slot_words(slot: str) -> str:
    return slot.removeprefix("k.").replace("_", " ") + "s"


# ------------------------------------------------------------------------------- run metadata
@dataclass
class Run:
    name: str
    experiment: str
    start: datetime
    end: datetime
    models: dict[str, dict[str, Any]]  # role -> manifest entry
    servers: dict[str, dict[str, Any]]  # role -> env.json entry (open-weight models only)
    params: dict[str, Any] = field(default_factory=dict)  # the manifest's run parameters


def _utc(s: str) -> datetime:
    return datetime.strptime(s.rstrip("Z"), "%Y-%m-%dT%H:%M:%S" if "-" in s else "%Y%m%dT%H%M%S")


def load_runs(runs_dir: Path) -> list[Run]:
    """Every run with a manifest (merged stages excluded). A run's start is the stamp of its name,
    its end the manifest's `created_utc`; `servers` is empty when the run kept no env.json."""
    out = []
    for man_path in sorted(runs_dir.glob("*/manifest.json")):
        name = man_path.parent.name
        stamp = re.search(r"(\d{8}T\d{6})Z", name)
        man = json.loads(man_path.read_text())
        if name.startswith("stage") or not stamp or "created_utc" not in man:
            continue
        env = read_json(man_path.parent / "env.json") or {}
        models = {r: m for r, m in (man.get("models") or {}).items() if isinstance(m, dict)}
        servers = {
            r: s
            for r, s in (env.get("models") or {}).items()
            if isinstance(s, dict) and "launched_utc" in s
        }
        out.append(
            Run(
                name,
                str(man.get("experiment")),
                _utc(stamp.group(1)),
                _utc(man["created_utc"]),
                models,
                servers,
                dict(man.get("params") or {}),
            )
        )
    return out


def _is_claude(model: str) -> bool:
    return model.startswith("claude")


def _union_hours(intervals: Iterable[tuple[datetime, datetime]]) -> float:
    total, cur = 0.0, None
    for s, e in sorted(intervals):
        if cur is None or s > cur[1]:
            if cur is not None:
                total += (cur[1] - cur[0]).total_seconds()
            cur = [s, e]
        else:
            cur[1] = max(cur[1], e)
    if cur is not None:
        total += (cur[1] - cur[0]).total_seconds()
    return total / 3600


def gpu_hours(runs: list[Run]) -> dict[str, float]:
    """GPU-hours: "total" (server held), "native" (the runs of the native memory systems) and
    "other" (every run that is not a native-system run), as the module docstring defines them."""
    held: dict[tuple[Any, ...], datetime] = {}
    for run in runs:
        for s in run.servers.values():
            key = (s["model"], str(s.get("gpus")), s.get("port"), s["launched_utc"])
            held[key] = max(held.get(key, run.end), run.end)
    per_gpu: dict[str, list[tuple[datetime, datetime]]] = defaultdict(list)
    for (_, gpus, _, launched), end in held.items():
        for g in gpus.split(","):
            per_gpu[g].append((_utc(launched), end))
    out = {"total": sum(_union_hours(v) for v in per_gpu.values()), "other": 0.0, "native": 0.0}
    active: dict[str, list[tuple[datetime, datetime, str]]] = defaultdict(list)
    for run in runs:
        family = "native" if run.experiment in NATIVE_EXPERIMENTS else "other"
        for g in {g for s in run.servers.values() for g in str(s.get("gpus")).split(",")}:
            active[g].append((run.start, run.end, family))
    for spans in active.values():
        cuts = sorted({t for s, e, _ in spans for t in (s, e)})
        for a, b in zip(cuts, cuts[1:], strict=False):
            fams = {f for s, e, f in spans if s <= a and e >= b}
            for f in fams:
                out[f] += (b - a).total_seconds() / 3600 / len(fams)
    return out


def claude_runs(runs: list[Run]) -> list[Run]:
    return [r for r in runs if any(_is_claude(str(m.get("model"))) for m in r.models.values())]


def claude_dates(runs: list[Run]) -> tuple[str, str] | None:
    """First and last Claude call of the runs that call Claude: the earliest `first_call_utc` and
    the latest end of such a run (a run ends after its last call)."""
    cr = claude_runs(runs)
    firsts = [
        _utc(m["first_call_utc"])
        for r in cr
        for m in r.models.values()
        if _is_claude(str(m.get("model"))) and m.get("first_call_utc")
    ]
    if not cr or not firsts:
        return None
    return f"{min(firsts):%Y-%m-%d}", f"{max(r.end for r in cr):%Y-%m-%d}"


def claude_usage(calls: Iterable[Mapping[str, Any]]) -> dict[str, float]:
    """Tokens and US$ of the Claude calls the logs record. A call sent online (`cached` false) is
    paid at the list price, twice the batch price. A request never sent online was answered through
    the Message Batches API and is paid once, at the batch price. Other models are skipped."""
    tokens, usd = 0.0, 0.0
    online: set[str] = set()
    batch: dict[str, tuple[float, float]] = {}
    for c in calls:
        if not _is_claude(str(c.get("model"))):
            continue
        pi, po = BATCH_PRICE[c["model"]]
        cost = (c["prompt_tokens"] * pi + c["completion_tokens"] * po) / 1e6
        if not c["cached"]:
            online.add(c["key"])
            tokens += c["prompt_tokens"] + c["completion_tokens"]
            usd += 2 * cost
        else:
            batch.setdefault(c["key"], (c["prompt_tokens"] + c["completion_tokens"], cost))
    for key, (t, cost) in batch.items():
        if key not in online:
            tokens += t
            usd += cost
    return {"tokens": tokens, "usd": usd}


def claude_calls(raw: Path, runs: list[Run]) -> list[dict[str, Any]] | None:
    """The Claude rows of the `calls.jsonl` of every run that calls Claude (None if one is
    missing)."""
    rows: list[dict[str, Any]] = []
    for run in claude_runs(runs):
        path = raw / run.name / "calls.jsonl"
        if not path.exists():
            return None
        rows += _jsonl(path, lambda r: _is_claude(str(r.get("model"))))
    return rows


def model_ids(runs: list[Run]) -> dict[str, str]:
    """Claude model name -> API identifier, as the manifests record them."""
    return {
        name: str(m["model"])
        for r in runs
        for m in r.models.values()
        if _is_claude(str(m.get("model")))
        for name in ("Sonnet", "Opus")
        if name.lower() in str(m["model"])
    }


def setup_facts(runs: list[Run], calls: list[dict[str, Any]] | None) -> str:
    ids = model_ids(runs)
    dates = claude_dates(runs)
    usage = claude_usage(calls) if calls is not None else None
    hours = gpu_hours(runs)

    def tt(s: str | None) -> str:
        return rf"\texttt{{{_tex(s)}}}" if s else MISSING

    lines = [
        "% Claude: API identifiers and call dates from the run manifests; tokens and US$ from",
        "% the Claude rows of the runs' calls.jsonl (online calls at twice the batch price of",
        "% memshift.claude_batch, batch-served requests once at the batch price). GPU-hours: as",
        "% the docstring of memshift.analysis.paper_extras defines them.",
        _macro("SonnetModelId", tt(ids.get("Sonnet"))),
        _macro("OpusModelId", tt(ids.get("Opus"))),
        _macro("ClaudeCallsFrom", dates[0] if dates else MISSING),
        _macro("ClaudeCallsTo", dates[1] if dates else MISSING),
        _macro("ClaudeTokensTotal", f"{usage['tokens'] / 1e6:.0f} million" if usage else MISSING),
        _macro("ClaudeSpendUSD", f"{usage['usd']:.0f}" if usage else MISSING),
        _macro("GpuModel", GPU_MODEL),
        _macro("GpuHoursTotal", f"{hours['total']:.0f}" if runs else MISSING),
        _macro("GpuHoursOtherRuns", f"{hours['other']:.0f}" if runs else MISSING),
        _macro("GpuHoursNativeSystems", f"{hours['native']:.0f}" if runs else MISSING),
    ]
    return "\n".join(lines) + "\n"


def _role_rank(words: str) -> tuple[int, str]:
    order = list(ROLE_WORDS.values())
    return (order.index(words) if words in order else len(order), words)


def run_roles(run: Run) -> dict[str, set[str]]:
    """Manifest role -> the roles its model plays in the run: the role itself; the writer also
    writes the programs of the D_m cells (`holdmem_D1s...`) when no program writer is named; and
    the models that `params.extraction` names rewrite the records into prose and extract their
    fields."""
    out = {role: {re.sub(r"_\d+$", "", role)} for role in run.models}
    cells = run.params.get("cells") or []
    if "writer" in out and "program_writer" not in out and any("D1s" in c for c in cells):
        out["writer"].add("program_writer")
    extraction = run.params.get("extraction") or {}
    for part in ("rewriter", "extractor"):  # one role of the model plays it: the writer if it can
        owners = [r for r, m in run.models.items() if m.get("model") == extraction.get(part)]
        if owners:
            out["writer" if "writer" in owners else owners[0]].add(part)
    return out


def model_size(model: str) -> str:
    """The parameter count that the repository id states (`Qwen/Qwen3.5-9B` -> `9B`) or SIZES
    gives; "---" for a model whose size neither gives (the API models)."""
    if model in SIZES:
        return SIZES[model]
    m = re.search(r"(?<![\d.])(\d+(?:\.\d+)?)[Bb](?![A-Za-z])", model.split("/")[-1])
    return f"{m.group(1)}B" if m else "---"


def reasoning(model: str, roles: set[str]) -> str:
    """A model's reasoning effort where reasoning is not off: the effort an open-weight family
    takes (`llm.default_extra_body`); for a Claude model, which thinks adaptively, the effort of a
    definition-item writer and of a program writer (`experiments.e1`). Empty when it is off."""
    if not _is_claude(model):
        return str(default_extra_body(model).get("reasoning_effort") or "")
    parts = []
    if ROLE_WORDS["defwriter"] in roles:
        parts.append(f"{DEFWRITER_BODY['output_config']['effort']} for definition items")
    program = CLAUDE_PROGRAM_BODY.get(model, {}).get("output_config", {}).get("effort")
    if program and ROLE_WORDS["program_writer"] in roles:
        parts.append(f"{program} for programs")
    return ", ".join(parts)


def _span(values: Iterable[int]) -> str:
    """One value, or the range of several ("---" for none)."""
    vals = sorted(set(values))
    if not vals:
        return "---"
    return f"{vals[0]:,}" if len(vals) == 1 else f"{vals[0]:,}--{vals[-1]:,}"


def tab_models(runs: list[Run]) -> str:
    """Every model the runs call: its repository identifier, or for a Claude model its name, with
    its citation, its size, the context it was served with (`env.json`, a range where runs differ;
    `API_CONTEXT` for a Claude model) and its roles (`run_roles`). Generative models before
    embedders, each by how many runs call it. The few reasoning settings that are not off are
    named in the notes."""
    roles: dict[str, set[str]] = defaultdict(set)
    count: Counter[str] = Counter()
    context: dict[str, set[int]] = defaultdict(set)
    for run in runs:
        played = run_roles(run)
        for role, m in run.models.items():
            model = str(m["model"])
            roles[model] |= {ROLE_WORDS.get(r, _tex(r)) for r in played[role]}
            count[model] += 1
            served = (run.servers.get(role) or {}).get("max_model_len")
            if served:
                context[model].add(int(served))
    for model, tokens in API_CONTEXT.items():
        if model in roles:
            context[model].add(tokens)
    embedder = ROLE_WORDS["embedding"]

    def order(model: str) -> tuple[bool, int, str]:
        return (embedder in roles[model], -count[model], model.lower())

    def row(model: str) -> str:
        cites = MODEL_CITES.get(model)
        name = rf"\mbox{{{_tex(MODEL_NAMES.get(model, model))}}}"
        size = model_size(model)
        return _row(
            name + (rf" \citep{{{','.join(cites)}}}" if cites else ""),
            r"\mtna" if size == "---" else size,  # a size no source states, centred
            _span(context[model]),
            ", ".join(sorted(roles[model], key=_role_rank)),
        )

    def short(model: str) -> str:
        return _tex(MODEL_NAMES.get(model, model.split("/")[-1]))

    weights = ", ".join(f"{short(m)} in {w}" for m, w in WEIGHTS.items())
    efforts = [
        f"{short(m)} (effort {_tex(e)})"
        for m in sorted(roles, key=order)
        if (e := reasoning(m, roles[m]))
    ]
    reasoning_on = (
        f"Reasoning is off except in {_and(efforts)}." if efforts else "Reasoning is off."
    )
    lines = [
        r"\begin{table*}[t]",
        r"\caption{Models, with the context each was served with (tokens) and its roles in the "
        r"runs.}",
        r"\label{tab:models}\label{tab:family-models}",
        r"\centering\mtsetup",
        r"\setlength{\tabcolsep}{4pt}",
        # names and roles with a hanging indent; size and context right-aligned
        r"\begin{mttabular}{@{}H{6.4cm}{1em} r r H{7.0cm}{1em}@{}}",
        r"\toprule",
        _row("Model", "Size", "Context", "Roles"),
        r"\midrule",
        *(row(m) for m in sorted(roles, key=order)),
        r"\bottomrule",
        r"\end{mttabular}",
        notes(
            rf"Open-weight models run under vLLM \citep{{kwon2023vllm}} in bfloat16 ({weights}) "
            rf"at temperature~0 with JSON-schema decoding. {reasoning_on} The Claude models "
            r"think adaptively. ---: not disclosed."
        ),
        r"\end{table*}",
    ]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=Path, default=Path("."))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    ap.add_argument("--raw", type=Path, default=None, help="raw run outputs (default: ROOT/runs)")
    ap.add_argument("--only", nargs="*", default=[], help="file names (tab_overview.tex, ...)")
    a = ap.parse_args()
    raw = a.raw or a.root / "runs"
    sources = json.loads((a.root / "results" / "sources.json").read_text())
    builders = {
        "tab_overview.tex": lambda: tab_overview(load(a.root, sources)),
        "example_world.tex": lambda: _example(raw),
        "tab_models.tex": lambda: tab_models(load_runs(a.root / "runs")),
        "setup_facts.tex": lambda: _facts(a.root / "runs", raw),
    }
    unknown = sorted(set(a.only) - set(builders))
    if unknown:
        raise SystemExit(f"unknown file(s): {', '.join(unknown)}")
    a.out.mkdir(parents=True, exist_ok=True)
    for name, build in builders.items():
        if a.only and name not in a.only:
            continue
        (a.out / name).write_text(HEAD + build())
        print(a.out / name)


def _example(raw: Path) -> str:
    gen = example_inputs()
    return example_world(gen, example_raw(raw, gen))


def _facts(runs_dir: Path, raw: Path) -> str:
    runs = load_runs(runs_dir)
    return setup_facts(runs, claude_calls(raw, runs))


if __name__ == "__main__":
    main()
