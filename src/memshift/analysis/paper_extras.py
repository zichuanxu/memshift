@dataclass(frozen=True)
class Example:
    """One definition item of one released world through one shift (the main experiment's run)."""

    seed: int = 1000
    branch: str = "def"
    slot: str = "k.active_project"
    weeks: int = 1  # the checkpoint after the fork
    run: str = "e1_test_s1000-1003_20260928T202242Z"
    cells: tuple[tuple[str, str], ...] = (
        ("holdmem_D0B0", r"\holdmem{}(0,0)"),
        ("holdmem_D0B1_source", r"\holdmem{}(0,1)"),
        ("holdmem_D1B1_source", r"\holdmem{}(1,1)"),
    )
    # one record per project of the gold value before the fork, and the record that joins after
    records: tuple[str, ...] = ("tasks:t028", "tasks:t020", "tasks:t006", "tasks:t003")
    stored_cell: str = "holdmem_D0B0"  # keeps the item written at t0 (B = 0 never re-derives it)


EXAMPLE = Example()
# a record in the gold value's dependency set (a check mark marks a correct answer)
DEP_MARK = r"$\bullet$"


def example_inputs(ex: Example = EXAMPLE) -> dict[str, Any]:
    """The generator's side of the example: the world, both probes, the records and definitions."""
    from memshift.gen.model import fmt_ts
    from memshift.gen.shifts import generate_branch
    from memshift.gen.state import SourceLog
    from memshift.probes import make_probes

    world = generate_branch(ex.seed, ex.branch)
    log = SourceLog(world.events)
    slot = next(s for s in world.slots if s.slot_id == ex.slot)
    times = (world.fork - timedelta(minutes=1), world.fork + timedelta(weeks=ex.weeks))
    probes = [make_probes(world, log, [t], slots=[slot])[0] for t in times]
    revs: dict[str, tuple[int, Any]] = {}
    for p in probes:
        for oid, rev in p.deps:
            revs.setdefault(oid, (rev, p))
    records = []
    for oid in ex.records:
        rev, p = revs[oid]
        obj = log.snapshot(p.as_of).objects[oid]
        if obj.revision != rev:
            raise ValueError(f"{oid}: revision {obj.revision} is not the dependency's {rev}")
        records.append((oid, rev, str(obj.payload["text"])))
    defs = world.kappa_defs[str(slot.kappa_id)]
    redefined = [
        t for t, k, v in world.kappa_log if k == slot.kappa_id and v == probes[1].kappa_version
    ]
    return {
        "world_id": world.world_id,
        "question": slot.question,
        "probes": [p.to_json() for p in probes],
        "times": [fmt_ts(t) for t in times],
        "definitions": {v: d.statement for v, d in defs.items()},
        "redefined": fmt_ts(redefined[0]) if redefined else None,
        "records": records,
    }


def _jsonl(path: Path, keep: Callable[[dict[str, Any]], bool]) -> list[dict[str, Any]]:
    """The rows of a JSONL file that `keep` accepts (raw outputs are large; most rows are not)."""
    with path.open(encoding="utf-8") as f:
        return [r for r in (json.loads(line) for line in f if line.strip()) if keep(r)]


def _one(rows: Iterable[dict[str, Any]], what: str) -> dict[str, Any]:
    row = next(iter(rows), None)
    if row is None:
        raise ValueError(f"the raw outputs hold no {what}")
    return row


def example_raw(raw: Path, gen: Mapping[str, Any], ex: Example = EXAMPLE) -> dict[str, Any] | None:
    """The run's side of the example: each cell's answer to both probes, the stored item and what
    each cell did at the checkpoint. None when the run's raw outputs are not under `raw`. The run's
    gold must be the generator's."""
    d = raw / ex.run
    if not all((d / f).exists() for f in ("probes.jsonl", "answers.jsonl", "items.jsonl")):
        return None
    wid = gen["world_id"]
    times = gen["times"]

    def ours(r: Mapping[str, Any]) -> bool:
        return r.get("world_id") == wid and r.get("branch") == ex.branch

    probes = _jsonl(d / "probes.jsonl", lambda r: ours(r) and r["fact_id"] == ex.slot)
    for p in gen["probes"]:
        row = next((r for r in probes if r["as_of"] == p["as_of"]), None)
        fields = ("gold_value", "gold_status", "deps", "kappa_version", "question_text")
        if row is None or any(row[f] != p[f] for f in fields):
            raise ValueError(f"{ex.run}: the run's probe at {p['as_of']} is not the generator's")
    cells = {c for c, _ in ex.cells}
    answers = _jsonl(
        d / "answers.jsonl",
        lambda r: ours(r) and r["fact_id"] == ex.slot and r["system"] in cells,
    )
    items = _jsonl(
        d / "items.jsonl",
        lambda r: ours(r) and r["slot_id"] == ex.slot and r["system"] in cells | {ex.stored_cell},
    )
    stored = _one(
        (
            r
            for r in items
            if r["system"] == ex.stored_cell
            and r["history"]
            and r["history"][0]["ts"] == times[0]
            and r["history"][0]["event"] == "derive"
        ),
        f"item of {ex.stored_cell} written at {times[0]}",
    )["s_k"]
    out: dict[str, Any] = {"stored": stored, "answers": {}, "events": {}}
    for cell, _ in ex.cells:
        out["answers"][cell] = [
            _one(
                (a for a in answers if a["system"] == cell and a["as_of"] == t),
                f"answer of {cell} at {t}",
            )
            for t in times
        ]
        out["events"][cell] = sorted(
            {
                h["event"]
                for r in items
                if r["system"] == cell
                for h in r["history"]
                if h["ts"] == times[1]
            }
        )
    return out


def _value(v: Any) -> str:
    if isinstance(v, list):
        return ", ".join(_tex(str(x)) for x in v) if v else "none"
    return _tex(str(v))


def _answer(a: Mapping[str, Any] | None, bold: bool = False) -> str:
    """An answer with its mark (status and value match gold or not); `bold` sets a correct
    answer's value in bold (the answer that follows a changed gold value)."""
    if a is None:
        return MISSING
    shown = (
        _value(a["value"])
        if a["status"] == "answer"
        else {"abstain": "abstains"}.get(a["status"], _tex(str(a["status"])))
    )
    if bold and a["contract_valid"]:
        shown = rf"\textbf{{{shown}}}"
    return shown + (r" \pass" if a["contract_valid"] else r" \fail")


def _gold(p: Mapping[str, Any]) -> str:
    """A probe's gold value, or its gold status when that is not an answer."""
    return _value(p["gold_value"]) if p["gold_status"] == "answer" else _tex(p["gold_status"])


def _did(events: list[str] | None) -> str:
    """What a cell did to the item at the checkpoint, from its history events."""
    if events is None:
        return MISSING
    if "invalidate" in events:
        return "invalidated, re-derived" if "repair" in events else "invalidated"
    return "kept" if not events else ", ".join(_tex(e) for e in events)


def _statement(s_k: str) -> str:
    """The first sentence of a stored item's statement (its bracketed header and evidence off)."""
    body = s_k.split("] ", 1)[1] if s_k.startswith("[") and "] " in s_k else s_k
    body = body.partition("Evidence: ")[0].strip()
    m = re.match(r"(.+?\.)(?:\s|$)", body)
    return _tex(m.group(1) if m else body)


def _fields(text: str) -> dict[str, str]:
    """The fields of a rendered record, one `Field: value` per line."""
    return dict(line.split(": ", 1) for line in text.splitlines() if ": " in line)


def _day(ts: str, year: bool = False) -> str:
    """A time stamp (`2026-06-28 11:30`) as a readable date (`Jun 28`, or `Jun 28, 2026`)."""
    d = datetime.strptime(ts[:10], "%Y-%m-%d")
    return f"{d:%b} {d.day}" + (f", {d.year}" if year else "")


def example_world(
    gen: Mapping[str, Any], raw: Mapping[str, Any] | None, ex: Example = EXAMPLE
) -> str:
    """The worked example in three blocks of one full-width table on one column grid: the probe
    and the definition in effect before and after the shift; the records by the fields that decide
    the gold value (no record ids) and whether each is in the gold value's dependency set under
    each version; the gold value, the stored item (written before the fork, so in that column) and
    each cell's answers with what the cell did at the checkpoint. The question, the same for both
    probes, comes first, above the before/after header. A bullet marks the dependency set, so that
    a check mark only marks a correct answer. The records block splits each of the other blocks'
    three columns into two, so its columns start where theirs do."""
    pre, post = gen["probes"]
    defs = gen["definitions"]
    # widths (cm): the stub; the two record columns under "before the fork" and the two under
    # "after"; the two Gold columns share what is left of the line (`\exG` each)
    stub, before, after = 2.0, (2.3, 3.6), (1.6, 3.4)
    cm = "{:.1f}cm".format
    b_w, a_w = cm(sum(before)), cm(sum(after))

    def split(widths: tuple[float, float]) -> str:
        """Two record columns that, with the space between them, are as wide as one block."""
        return rf"P{{{cm(widths[0])}}}P{{\dimexpr{cm(widths[1])}-2\tabcolsep\relax}}"

    grid = rf"@{{}}P{{{cm(stub)}}} {split(before)} {split(after)} C{{\exG}}C{{\exG}}@{{}}"

    def block(text: str, width: str, cols: int = 2, last: bool = False) -> str:
        """`text` across `cols` grid columns, a paragraph `width` wide."""
        return rf"\multicolumn{{{cols}}}{{P{{{width}}}{'@{}' if last else ''}}}{{{text}}}"

    def first(text: str) -> str:  # before the fork
        return block(text, b_w)

    def second(text: str) -> str:  # after the shift
        return block(text, a_w)

    def did(text: str) -> str:  # what the memory did
        return block(text, r"\dimexpr2\exG+2\tabcolsep\relax", last=True)

    def rest(text: str) -> str:  # after the shift, to the right edge
        width = rf"\dimexpr\linewidth-{cm(stub)}-{b_w}-4\tabcolsep\relax"
        return block(text, width, 4, last=True)

    def full(text: str) -> str:  # every column after the stub
        return block(text, rf"\dimexpr\linewidth-{cm(stub)}-2\tabcolsep\relax", 6, last=True)

    def definition(p: Mapping[str, Any]) -> str:
        v = str(p["kappa_version"])
