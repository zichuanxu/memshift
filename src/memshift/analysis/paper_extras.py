def _level(x: float | None) -> str:
    """A rate in percent with one decimal, as the `pct` macros print it (without the sign)."""
    return MISSING if x is None or x != x else f"{100 * x:.1f}"


TEX_CHARS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def _tex(s: str) -> str:
    """Plain text (names, record text, model output) as LaTeX; straight double quotes alternate
    between opening and closing quotes."""
    out, opened = [], False
    for ch in s:
        if ch == '"':
            out.append("''" if opened else "``")
            opened = not opened
        else:
            out.append(TEX_CHARS.get(ch, ch))
    return "".join(out)


