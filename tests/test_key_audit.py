# The values of the decision-log row (all / definition / structured / free text), in percent:
# false invalidation per branch and key; re-derivations per world (all / definition)
LOGGED_FALSE = {
    ("Src", "Source"): ("99.7", "98.6", "99.7", "100.0"),
    ("Src", "Oracle"): ("16.8", "50.3", "16.4", "1.5"),
    ("Def", "Source"): ("99.3", "95.7", "99.3", "100.0"),
    ("Def", "Oracle"): ("4.3", "61.3", "2.9", "1.1"),
    ("Orphan", "Source"): ("100.0", "100.0", "100.0", "100.0"),
    ("Orphan", "Oracle"): ("7.0", "49.4", "3.7", "1.1"),
}
LOGGED_SCOPE_FALSE = {"Src": "53.1", "Def": "64.5", "Orphan": "52.3"}
LOGGED_PER_WORLD = {
    ("Src", "Source"): ("190.0", "23.5"),
    ("Def", "Source"): ("189.6", "23.5"),
    ("Orphan", "Source"): ("190.4", "23.6"),
    ("Src", "Oracle"): ("38.2", "18.9"),
    ("Def", "Oracle"): ("27.7", "20.8"),
    ("Orphan", "Oracle"): ("40.3", "18.7"),
    ("Src", "Scope"): (None, "19.1"),
    ("Def", "Scope"): (None, "21.5"),
    ("Orphan", "Scope"): (None, "19.0"),
}
LOGGED_COUNTS = {"Src": ("1,168", "2,672"), "Def": ("558", "3,282"), "Orphan": ("1,767", "2,073")}


def test_staged_audit_reproduces_the_pinned_values(staged):
    m = ka.numbers(staged)
    assert MISSING not in m.values()
    for (b, k), values in LOGGED_FALSE.items():
        for cls, value in zip(("All", "Definition", "Rule", "Free"), values, strict=True):
            assert m[f"KeyAuditFalse{k}{b}{cls}"] == value + "\\%", (b, k, cls)
    for b, value in LOGGED_SCOPE_FALSE.items():
        assert m[f"KeyAuditFalseScope{b}Definition"] == value + "\\%"
    for (b, k), (all_, definition) in LOGGED_PER_WORLD.items():
        if all_ is not None:
            assert m[f"KeyAuditRederivWorld{k}{b}All"] == all_, (b, k)
        assert m[f"KeyAuditRederivWorld{k}{b}Definition"] == definition, (b, k)
    for b, (changed, unchanged) in LOGGED_COUNTS.items():
        assert (m[f"KeyAuditChanged{b}"], m[f"KeyAuditUnchanged{b}"]) == (changed, unchanged)
    assert m["KeyAuditWorlds"] == "20"
    assert m["KeyAuditMissedMax"] == "0.0\\%"  # no key misses a change, in any branch
    # structured items after S_src: 344 re-derivations of the oracle key against 2,930
    assert m["KeyAuditRederivOracleSrcRule"] == "344"
    assert m["KeyAuditRederivSourceSrcRule"] == "2,930"


def test_share_of_definition_checkpoints_the_oracle_key_rederives(staged):
    m = ka.numbers(staged)
    assert m["KeyAuditDefCheckpointsSrc"] == "480"
    shares = {b: m[f"KeyAuditDefShareOracle{b}"] for b in ("Src", "Def", "Orphan")}
    assert shares == {"Src": "78.5\\%", "Def": "86.5\\%", "Orphan": "77.7\\%"}
    assert m["KeyAuditDefShareOracleMin"] == "77.7\\%"
    assert m["KeyAuditDefShareOracleMax"] == "86.5\\%"  # 415 of 480, 86.46 exactly


def test_rates_are_rounded_half_up_from_the_exact_ratio():
    assert ka._half_up(469, 20, 1, 1) == "23.5"  # 23.45; binary float formatting gives 23.4
    assert ka._half_up(805, 20, 1, 1) == "40.3"  # 40.25
    assert ka._pct(1, 8) == "12.5\\%"
    assert ka._pct(0, 7) == "0.0\\%"
    assert ka._pct(3, 0) == MISSING


def test_the_macros_come_from_the_counts_not_the_stored_rates(staged):
    tampered = json.loads(json.dumps(staged))
    tampered["src"]["gold"]["rule"]["false_invalidation"] = 0.5  # the stored rate is not read
    assert ka.numbers(tampered) == ka.numbers(staged)
    tampered["src"]["gold"]["rule"]["unchanged_detected"] += 100
    assert (
        ka.numbers(tampered)["KeyAuditFalseOracleSrcRule"]
        != (ka.numbers(staged)["KeyAuditFalseOracleSrcRule"])
    )


def test_table_is_wellformed_and_shows_the_staged_values(staged):
    tex = ka.tab_keyaudit(staged)
    check_tex(tex)
    assert MISSING not in tex
    assert r"\label{tab:keyaudit}" in tex
    assert "99.7 & 98.6 & 99.7 & 100.0" in tex and "16.8 & 50.3 & 16.4 & 1.5" in tex
    # the changed and unchanged item-times of each shift are columns, on the shift's first line
    assert r"$\Ssrc$ & 1,168 & 2,672 & source key" in tex and "480 definition" in tex
    assert tex.count("scope") >= 3  # one scope row per branch, definition items only


def test_table_gives_the_single_field_totals_the_text_quotes(staged):
    tex = ka.tab_keyaudit(staged)
    m = ka.numbers(staged)
    rows = [ln.removesuffix(r" \\").split(" & ") for ln in tex.splitlines() if " & " in ln]
    src = next(r for r in rows if r[0] == r"$\Ssrc$" and r[3] == "source key")
    oracle = rows[rows.index(src) + 1]
    # Section 5.3 quotes these two totals over the 20 worlds; they come from the same counts
    assert src[10] == m["KeyAuditRederivSourceSrcRule"] == "2,930"
    assert oracle[:4] == ["", "", "", "oracle"]
    assert oracle[10] == m["KeyAuditRederivOracleSrcRule"] == "344"
    # shift, its two counts, key, four rates, three counts, share
    assert all(len(r) == 12 for r in rows[2:])
    # the header is split over lines: re-derivations, per world / in the worlds, then the columns
    assert r"\multicolumn{3}{c}{re-derivations}" in tex
    assert r"\multicolumn{4}{c}{unchanged item-times}" in tex
    assert r"\multicolumn{4}{c}{invalidated (\%)}" in tex
    assert r"\multicolumn{2}{c}{per world} & 20 worlds & share \\" in tex
    caption = tex.split(r"\label{tab:keyaudit}")[0]
    for term in (
        "What each key invalidates",
        "audited without a model",
        "Re-derivations",
        "Def.\\ share",
    ):
        assert term in caption, term
    assert "item-checkpoint" not in tex and "item-times" in caption


def test_stage_writer_records_command_seeds_and_code(tmp_path):
    result = audit([5], ("def",), months=3)
    write_stage(tmp_path / "stage", result, "python -m memshift.analysis.e1_keys ...", "5")
    manifest = json.loads((tmp_path / "stage" / "manifest.json").read_text())
    assert manifest["command"].endswith("...") and manifest["seeds"] == "5"
    assert manifest["branches"] == ["def"] and manifest["sources"] == []
    assert set(manifest["files_sha256"]) == {"analysis/e1_keys.json"}
    assert {"commit", "dirty"} == set(manifest["analysis_code"])
    stored = json.loads((tmp_path / "stage" / "analysis" / "e1_keys.json").read_text())
    assert stored == json.loads(json.dumps(result))


@pytest.mark.paper
def test_committed_generated_files_are_current(staged):
    assert (ROOT / "paper/generated/tab_keyaudit.tex").read_text() == HEAD + ka.tab_keyaudit(staged)
    numbers = (ROOT / "paper/generated/numbers.tex").read_text()
    for name, value in ka.numbers(staged).items():
        assert _macro(name, value) in numbers, name


