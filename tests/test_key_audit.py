from tests.test_paper_stage4 import check_tex

ROOT = Path(__file__).resolve().parents[1]
SOURCES = json.loads((ROOT / "results/sources.json").read_text())
HEAD = "% generated by memshift.analysis.paper_tables; do not edit\n"


@pytest.fixture(scope="module")
def staged() -> dict:
    view = ka.load(ROOT, SOURCES)
    assert view is not None
    return view


def test_unstaged_audit_renders_only_missing_markers():
    macros = ka.numbers(None)
    assert len(macros) > 100
    for name, value in macros.items():
        _macro(name, value)  # letters only
        assert name.startswith("KeyAudit") and value == MISSING, (name, value)
    tex = ka.tab_keyaudit(None)
    assert MISSING in tex
    check_tex(tex)


